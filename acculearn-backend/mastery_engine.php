<?php
require_once __DIR__ . '/config.php';
require_once __DIR__ . '/db.php';

class MasteryEngine {

    /** A mastered competency with at least this CMI is flagged as a likely misconception. */
    const CMI_MISCONCEPTION_THRESHOLD = 0.20;

    /** A mastered competency with at least this GI is treated as guessing-driven. */
    const GI_GUESSING_THRESHOLD = 0.20;

    /**
     * Which learning-pathway rule decides LP and mastery.
     *
     * 'paper'
     *   The thesis Chapter 3 formula, LP = f(PR, CM, GI, CMI). Mastery is the
     *   pooled CM score against the 85/75 thresholds, the prerequisite opens
     *   on the previous competency being Mastered, and a high GI or CMI holds
     *   an otherwise-mastered competency at Reinforcement Practice.
     *
     *   THIS IS THE RULE THAT PRODUCED THE STUDY RESULTS. Every learning track
     *   stored from the 22 June - 31 July 2026 intervention was generated by
     *   it, so it is what Chapter 4 reports on and what a demonstration should
     *   show if the demonstration is meant to match the paper.
     *
     * 'quizpassing'
     *   The revision made on 2026-08-09, AFTER data collection closed. Mastery
     *   is earned by passing every formative plus the summative; CM/CMI/GI
     *   survive only as diagnostics that shape wording. Pedagogically this is
     *   the stronger rule - a pooled average can mask an unpassed quiz - but
     *   it is NOT what the paper describes and NOT what generated the results.
     *
     * Restored to 'paper' on 2026-09-20 so the live system matches the
     * manuscript. Flip this one constant to replay the revised behaviour;
     * nothing else needs to change.
     */
    const LP_MODE = 'paper';

    /**
     * Who makes the mastery / pathway / ordering decisions.
     *
     * 'ai'
     *   DecisionEngine (decision_engine.php): the model is handed the
     *   evidence for all seven competencies and decides mastery tier, LP,
     *   adaptive order and priority group itself, with no formula in its
     *   prompt. Decisions are made when a track is (re)generated - after each
     *   quiz submission and on pre-test entry - and STORED in
     *   acculearn_learning_tracks. The quiz gate and unlock-group sync read
     *   the stored decision (currentPathway()) rather than recomputing.
     *   Switched on 2026-09-22.
     *
     * 'rule'
     *   The LP_MODE formula above decides everything, computed live on every
     *   read. This is how the system ran during the study and is still the
     *   FALLBACK whenever the model is unavailable or a student has no stored
     *   decision yet (a brand-new student before their first submission).
     *
     * The formula code is kept in full for that fallback, so flipping this
     * back to 'rule' restores the study-era behaviour without a redeploy of
     * anything else.
     */
    const DECISION_MODE = 'ai';

    /**
     * Fewest answered items before a competency may be called "Mastered".
     *
     * CM is correct/answered, so the DENOMINATOR is whatever evidence exists -
     * not the intended test length. With a partially entered pre-test that is
     * actively dangerous: enter one correct item for a competency and CM is
     * 1/1 = 100% = Mastered, which satisfies the prerequisite check and
     * unlocks the next competency on the strength of a single question.
     * (Real example on this site: teststudent has competency 2 recorded as
     * 1 correct out of 2 answered = 50%. Had that one item been the only one
     * entered and correct, the chain would have opened.)
     *
     * 8 is the floor because of how the thresholds divide. With n items CM can
     * only land on multiples of 1/n, and below 8 items no score falls in the
     * 75-84% "Developing" band while "Mastered" (>=85%) demands a perfect
     * paper: at n=5 mastery needs 5/5, at n=7 the Developing band cannot be
     * reached at all. From n=8, 7/8 = 87.5% is Mastered and 6/8 = 75% is
     * Developing, so both outcomes are actually reachable.
     *
     * Below this, a competency reports "Insufficient Evidence": CM/CMI/GI are
     * still computed and shown, but the competency is never treated as
     * Mastered and therefore never unlocks what follows it.
     */
    const MIN_ITEMS_FOR_MASTERY = 8;

    /**
     * Per-request memo for competencyQuizStatus(), keyed "userid:competencyid".
     *
     * The same status gets asked for repeatedly inside one request:
     * computeLearningPathway() reads a competency's own status AND (via
     * checkPrerequisite) the status of the competency before it, so a full
     * 7-competency track recomputed ~13 identical status queries. Scoped to
     * the instance, so a gradebook change part-way through a request can
     * never be masked by a stale entry from an earlier request.
     */
    private $quizstatuscache = [];

    /**
     * Per-quiz pass status for every quiz belonging to a competency.
     *
     * A competency is Mastered only when EVERY formative quiz AND the
     * summative quiz have been passed - not when a pooled average crosses
     * 85%. Passing marks live on the Moodle grade item (formatives 80%,
     * summative 85%), so this reads the gradebook rather than recomputing
     * scores: that way a teacher's manual grade override (teacher_review.php)
     * correctly counts as a pass, and Moodle's "Highest grade" setting
     * already picks the student's best attempt for us.
     *
     * Summative vs formative is decided by quiz name. Verified consistent
     * across all 7 courses: each has exactly one quiz named "Summative Quiz"
     * plus 2-5 "Formative Quiz N". If a course is ever renamed so that no
     * quiz matches, 'summative_passed' stays false and the competency simply
     * cannot be mastered - it fails closed rather than silently opening the
     * chain.
     */
    public function competencyQuizStatus($userid, $competencyId) {
        $key = (int) $userid . ':' . (int) $competencyId;
        if (!array_key_exists($key, $this->quizstatuscache)) {
            $this->quizstatuscache[$key] = $this->readCompetencyQuizStatus($userid, $competencyId);
        }
        return $this->quizstatuscache[$key];
    }

    /** Uncached body of competencyQuizStatus(). */
    private function readCompetencyQuizStatus($userid, $competencyId) {
        $db = get_db();

        $stmt = $db->prepare("
            SELECT c.courseid FROM acculearn_competencies c WHERE c.id = ?");
        $stmt->execute([$competencyId]);
        $comp = $stmt->fetch();

        $empty = [
            'quizzes' => [], 'formatives_passed' => false,
            'summative_passed' => false, 'all_passed' => false,
            'passed_count' => 0, 'total_count' => 0,
        ];
        if (!$comp || !$comp->courseid) {
            return $empty;
        }

        $stmt = $db->prepare("
            SELECT q.id, q.name, gi.grademax, gi.gradepass, gg.finalgrade
              FROM mdl_quiz q
              JOIN mdl_grade_items gi
                ON gi.iteminstance = q.id AND gi.itemmodule = 'quiz'
               AND gi.itemtype = 'mod' AND gi.courseid = q.course
         LEFT JOIN mdl_grade_grades gg ON gg.itemid = gi.id AND gg.userid = ?
             WHERE q.course = ?
          ORDER BY q.id");
        $stmt->execute([$userid, $comp->courseid]);
        $rows = $stmt->fetchAll();

        if (!$rows) {
            return $empty;
        }

        $lessonlocks = $this->lessonLocks($userid, $comp->courseid);

        $quizzes = [];
        $formatives = [];
        $summatives = [];
        foreach ($rows as $r) {
            $issummative = (stripos($r->name, 'summative') !== false);
            // A pass needs a real grade AND a configured passing mark. If no
            // gradepass is set the quiz cannot be passed - deliberately fails
            // closed, since an unset mark used to be the norm here.
            $passed = ($r->finalgrade !== null)
                && ((float) $r->gradepass > 0)
                && ((float) $r->finalgrade >= (float) $r->gradepass);

            $q = [
                'id' => (int) $r->id,
                'name' => $r->name,
                'is_summative' => $issummative,
                'grade' => $r->finalgrade === null ? null : round((float) $r->finalgrade, 2),
                'grademax' => round((float) $r->grademax, 2),
                'gradepass' => round((float) $r->gradepass, 2),
                'attempted' => $r->finalgrade !== null,
                'passed' => $passed,
                // Mirrors quizaccess_acculearn's lesson gate so the track and
                // the quiz page can never tell the student different stories
                // about why a quiz is not open yet. Summatives are excluded
                // for the same reason they are there: they are gated on the
                // formatives, which are themselves gated on the lessons.
                'lesson_locked' => !$issummative && isset($lessonlocks[(int) $r->id]),
                'lesson_name' => $issummative ? null : ($lessonlocks[(int) $r->id]->name ?? null),
                'lesson_cmid' => $issummative ? null : ($lessonlocks[(int) $r->id]->cmid ?? null),
            ];
            $quizzes[] = $q;
            if ($issummative) { $summatives[] = $q; } else { $formatives[] = $q; }
        }

        $formativespassed = !empty($formatives);
        foreach ($formatives as $q) {
            if (!$q['passed']) { $formativespassed = false; break; }
        }

        $summativepassed = !empty($summatives);
        foreach ($summatives as $q) {
            if (!$q['passed']) { $summativepassed = false; break; }
        }

        $passedcount = 0;
        foreach ($quizzes as $q) { if ($q['passed']) { $passedcount++; } }

        return [
            'quizzes' => $quizzes,
            'formatives_passed' => $formativespassed,
            'summative_passed' => $summativepassed,
            'all_passed' => ($formativespassed && $summativepassed),
            'passed_count' => $passedcount,
            'total_count' => count($quizzes),
        ];
    }

    /**
     * Quizzes in a course whose lesson the student has not finished yet.
     *
     * The read-only counterpart to quizaccess_acculearn's lesson gate: each
     * course section pairs one SCORM lesson with one formative quiz, and the
     * quiz does not open until the package reports the student completed it
     * (SCORM 1.2 cmi.core.lesson_status / SCORM 2004 cmi.completion_status).
     * Reported here so the learning track can say WHICH lesson is holding a
     * quiz shut, instead of leaving it looking merely untaken.
     *
     * Hidden lessons are ignored, matching the rule - a lesson a teacher took
     * out of the course must not go on blocking the quiz beside it.
     *
     * @return stdClass[] keyed by quiz id, each {cmid, name} of the first
     *   unfinished lesson in that quiz's section. Quizzes whose lesson is done
     *   (or that have no lesson) are simply absent.
     */
    private function lessonLocks($userid, $courseid) {
        $db = get_db();
        $stmt = $db->prepare("
            SELECT q.id AS quizid, cms.id AS lessoncmid, s.name AS lessonname,
                   MAX(CASE WHEN e.element IN ('cmi.core.lesson_status', 'cmi.completion_status')
                             AND v.value IN ('completed', 'passed') THEN 1 ELSE 0 END) AS finished
              FROM mdl_quiz q
              JOIN mdl_modules mq ON mq.name = 'quiz'
              JOIN mdl_course_modules cmq
                ON cmq.instance = q.id AND cmq.module = mq.id AND cmq.deletioninprogress = 0
              JOIN mdl_modules ms ON ms.name = 'scorm'
              JOIN mdl_course_modules cms
                ON cms.section = cmq.section AND cms.module = ms.id
               AND cms.visible = 1 AND cms.deletioninprogress = 0
              JOIN mdl_scorm s ON s.id = cms.instance
         LEFT JOIN mdl_scorm_attempt a ON a.scormid = s.id AND a.userid = ?
         LEFT JOIN mdl_scorm_scoes_value v ON v.attemptid = a.id
         LEFT JOIN mdl_scorm_element e ON e.id = v.elementid
             WHERE q.course = ?
          GROUP BY q.id, cms.id, s.name
          ORDER BY q.id, cms.id");
        $stmt->execute([$userid, $courseid]);

        $locks = [];
        foreach ($stmt->fetchAll() as $r) {
            if ((int) $r->finished === 1) {
                continue;
            }
            // First unfinished lesson in the section wins, matching the rule,
            // which returns the first one it finds in the same order.
            if (isset($locks[(int) $r->quizid])) {
                continue;
            }
            $lock = new stdClass();
            $lock->cmid = (int) $r->lessoncmid;
            $lock->name = $r->lessonname;
            $locks[(int) $r->quizid] = $lock;
        }
        return $locks;
    }

    /**
     * Sub-select yielding exactly ONE quiz attempt id per quiz for a user:
     * their BEST finished attempt, ties broken by the later attempt number.
     *
     * This exists because mastery was previously computed over EVERY attempt
     * a student had ever made. mdl_qbehaviour_confidence stores one row per
     * (attemptid, questionattemptid), so each retake APPENDED a fresh set of
     * rows rather than superseding the last one, and CM was correct/total
     * over the whole accumulated pile. A student who scored 0/5 and then 5/5
     * twice computed as 10/15 = 66.7%, so three attempts capped them below
     * the 85% Mastered threshold - permanently, since competencies form a
     * prerequisite chain and the quizaccess rule blocks a new attempt until
     * the prerequisite is Mastered. Retaking to improve, which the whole
     * three-retake design assumes, could therefore only ever hurt.
     *
     * "Best attempt" matches the gradebook: all 29 quizzes are configured
     * grademethod = 1 (Highest grade), so the mastery panel and the Moodle
     * grade now agree rather than contradicting each other.
     *
     * preview = 0 excludes teacher preview attempts, which are not student
     * evidence and would otherwise pollute a student's own figures if a
     * teacher previewed while logged in as them.
     */
    private function bestAttemptSubquery() {
        return "
            SELECT id FROM (
                SELECT id,
                       ROW_NUMBER() OVER (
                           PARTITION BY quiz
                           ORDER BY sumgrades DESC, attempt DESC
                       ) AS rn
                  FROM mdl_quiz_attempts
                 WHERE userid = ? AND state = 'finished' AND preview = 0
            ) ranked
            WHERE rn = 1
        ";
    }

    public function computeCompetencyStats($userid, $competencyId) {
        $db = get_db();
        $best = $this->bestAttemptSubquery();
        $sql = "
            SELECT
                qbc.confidence,
                CASE laststep.state
                    WHEN 'gradedright' THEN 1
                    WHEN 'gradedpartial' THEN 0
                    WHEN 'gradedwrong' THEN 0
                    ELSE 0
                END AS is_correct
            FROM mdl_qbehaviour_confidence qbc
            JOIN mdl_question_attempts qas ON qas.id = qbc.questionattemptid
            JOIN acculearn_question_competency qc ON qc.questionid = qas.questionid
            JOIN ($best) best ON best.id = qbc.attemptid
            LEFT JOIN mdl_question_attempt_steps laststep
                ON laststep.id = (
                    SELECT id FROM mdl_question_attempt_steps
                    WHERE questionattemptid = qbc.questionattemptid
                    ORDER BY sequencenumber DESC LIMIT 1
                )
            WHERE qbc.userid = ? AND qc.competency_id = ?
        ";
        $stmt = $db->prepare($sql);
        // The subquery's placeholder comes first in the SQL text, so $userid
        // is bound twice: once for the best-attempt filter, once for the
        // outer confidence rows.
        $stmt->execute([$userid, $userid, $competencyId]);
        $rows = $stmt->fetchAll();

        return $this->summarize($rows);
    }

    public function computeCompetencyStatsFromPretest($userid, $competencyId) {
        $db = get_db();
        $sql = "
            SELECT confidence, is_correct
            FROM acculearn_pretest_responses
            WHERE userid = ? AND competency_id = ?
        ";
        $stmt = $db->prepare($sql);
        $stmt->execute([$userid, $competencyId]);
        $rows = $stmt->fetchAll();

        return $this->summarize($rows);
    }

    private function summarize($rows) {
        $total = count($rows);
        if ($total === 0) {
            return ['cm' => null, 'cmi' => null, 'gi' => null, 'attempted' => 0];
        }

        $correctCount = 0;
        $highConfidenceIncorrect = 0;
        $lowConfidenceCorrect = 0;

        foreach ($rows as $r) {
            $correct = (bool) $r->is_correct;
            if ($correct) $correctCount++;
            if (!$correct && $r->confidence == 3) $highConfidenceIncorrect++;
            if ($correct && $r->confidence == 1) $lowConfidenceCorrect++;
        }

        return [
            'cm' => round(($correctCount / $total) * 100, 1),
            'cmi' => round($highConfidenceIncorrect / $total, 3),
            'gi' => round($lowConfidenceCorrect / $total, 3),
            'attempted' => $total,
        ];
    }

    /**
     * @param float|null $cm
     * @param int|null $attempted How many items the CM was computed over. When
     *   supplied and below MIN_ITEMS_FOR_MASTERY, the competency cannot be
     *   reported as Mastered - see that constant for why. Left optional so
     *   existing callers that only have a CM keep working unchanged.
     */
    public function classifyMastery($cm, $attempted = null) {
        if ($cm === null) return 'Not Attempted';
        if ($attempted !== null && $attempted > 0 && $attempted < self::MIN_ITEMS_FOR_MASTERY) {
            // Genuinely weak performance is still reportable on thin evidence -
            // it is only the claim of MASTERY (which unlocks the chain) that
            // needs a real sample behind it.
            return ($cm >= 75) ? 'Insufficient Evidence' : 'Needs Improvement';
        }
        if ($cm >= 85) return 'Mastered';
        if ($cm >= 75) return 'Developing';
        return 'Needs Improvement';
    }

    /**
     * Descriptive band for a competency that has NOT been mastered.
     *
     * Mastery is now decided solely by passing every quiz, so this never
     * returns 'Mastered' - a high pooled average with quizzes still
     * outstanding is 'Developing', not a pass. Keeping the two separate is
     * what stops the contradiction of a competency reading "Mastered" while
     * the next one sits visibly Locked.
     */
    private function bandBelowMastered($cm, $attempted) {
        if ($cm === null) return 'Not Attempted';
        if ($attempted > 0 && $attempted < self::MIN_ITEMS_FOR_MASTERY) {
            return ($cm >= 75) ? 'Insufficient Evidence' : 'Needs Improvement';
        }
        return ($cm >= 75) ? 'Developing' : 'Needs Improvement';
    }

    public function checkPrerequisite($userid, $competencyId, $source = 'quiz') {
        $db = get_db();
        $stmt = $db->prepare("SELECT prerequisite_id FROM acculearn_competencies WHERE id = ?");
        $stmt->execute([$competencyId]);
        $comp = $stmt->fetch();

        if (!$comp || !$comp->prerequisite_id) {
            return 1;
        }

        if (self::LP_MODE === 'paper') {
            // Chapter 3: "PR = 1 if the prerequisite competency's mastery is
            // Mastered (CM >= 85), else 0." Unlike the quizpassing rule below,
            // this DOES honour $source, because the paper's pre-test track is
            // generated from pre-test evidence alone - there are no quiz
            // attempts in existence at that point, so a quiz-passing
            // prerequisite would hold every competency at LP=1 and the
            // pre-test track would carry no information at all.
            $prereqstats = ($source === 'pretest')
                ? $this->computeCompetencyStatsFromPretest($userid, $comp->prerequisite_id)
                : $this->computeCompetencyStats($userid, $comp->prerequisite_id);

            return $this->classifyMastery($prereqstats['cm'], $prereqstats['attempted']) === 'Mastered' ? 1 : 0;
        }

        // Unlocking is now decided ONLY by whether the prerequisite
        // competency's quizzes were actually passed - every formative plus
        // the summative. Note this ignores $source deliberately: a strong
        // pre-test is a placement signal, not a demonstration, so it can
        // reorder a student's path but must never open the next competency.
        $prereq = $this->competencyQuizStatus($userid, $comp->prerequisite_id);

        return $prereq['all_passed'] ? 1 : 0;
    }

    /**
     * The FACTS about one competency, with no decision attached: the three
     * CBM indices and what they rest on, plus the per-quiz pass record. This
     * is what the AI decision model is given, and what the pages refresh live
     * on top of a stored decision (applyLiveEvidence()).
     *
     * Keys match the corresponding fields of a stored track row, so evidence
     * and decision can be merged by plain array union.
     */
    public function computeEvidence($userid, $competencyId, $source = 'quiz') {
        $stats = ($source === 'pretest')
            ? $this->computeCompetencyStatsFromPretest($userid, $competencyId)
            : $this->computeCompetencyStats($userid, $competencyId);

        // Shown on the track page whichever rule decides the pathway, so the
        // student can still see exactly which quizzes remain outstanding.
        $quizstatus = $this->competencyQuizStatus($userid, $competencyId);

        return [
            'competency_id' => (int) $competencyId,
            'cm' => $stats['cm'],
            'cmi' => $stats['cmi'],
            'gi' => $stats['gi'],
            'attempted' => $stats['attempted'],
            'quizzes' => $quizstatus['quizzes'],
            'formatives_passed' => $quizstatus['formatives_passed'],
            'summative_passed' => $quizstatus['summative_passed'],
            'all_passed' => $quizstatus['all_passed'],
            'quizzes_passed' => $quizstatus['passed_count'],
            'quizzes_total' => $quizstatus['total_count'],
        ];
    }

    /**
     * computeEvidence() for every competency, in curriculum order, with the
     * competency's name, sequence, course and prerequisite attached.
     */
    public function computeFullEvidence($userid, $source = 'quiz') {
        $db = get_db();
        $competencies = $db->query("SELECT * FROM acculearn_competencies ORDER BY sequence")->fetchAll();

        $evidence = [];
        foreach ($competencies as $c) {
            $row = $this->computeEvidence($userid, $c->id, $source);
            $row['competency_name'] = $c->name;
            $row['sequence'] = (int) $c->sequence;
            $row['courseid'] = $c->courseid === null ? null : (int) $c->courseid;
            $row['prerequisite_id'] = $c->prerequisite_id === null ? null : (int) $c->prerequisite_id;
            $evidence[] = $row;
        }
        return $evidence;
    }

    /**
     * Fingerprint of the evidence a decision was made on.
     *
     * A stored track is only re-decided (one model call) when this changes.
     * It covers exactly the inputs the model sees - the three indices, the
     * item count and each quiz's attempted/passed state - and nothing the
     * model produces, so a re-run that happens to decide differently on the
     * same facts does not itself trigger another run.
     *
     * Accepts evidence rows or full track rows (a superset) alike.
     */
    public static function evidenceSignature(array $rows) {
        $sig = [];
        foreach ($rows as $t) {
            $quizzes = [];
            foreach (($t['quizzes'] ?? []) as $q) {
                $quizzes[(int) $q['id']] = [
                    !empty($q['attempted']) ? 1 : 0,
                    !empty($q['passed']) ? 1 : 0,
                ];
            }
            ksort($quizzes);
            $sig[(int) $t['competency_id']] = [
                $t['cm'] ?? null,
                $t['cmi'] ?? null,
                $t['gi'] ?? null,
                (int) ($t['attempted'] ?? 0),
                $quizzes,
            ];
        }
        ksort($sig);
        return sha1(json_encode($sig));
    }

    /**
     * The decision currently in force for one competency - what the quiz
     * gate and the unlock-group sync act on.
     *
     * Under DECISION_MODE 'ai' this is the STORED decision from the
     * student's latest track, which the model made the last time their
     * evidence changed. It is read, not recomputed: recomputing would mean a
     * model call on every quiz page view. The formula is used only when the
     * student has no AI-decided track yet (nothing submitted, no pre-test
     * entered, or every model call so far has failed), so a new student is
     * gated exactly as before rather than not at all.
     *
     * A stored decision can trail the gradebook by the time it takes the
     * ad-hoc task to run after a submission (about a minute) or, for a change
     * made outside a submission such as a teacher's regrade, until the next
     * scheduled refresh (sync_unlock_groups_task, every 15 minutes).
     *
     * @return array a track row (lp, mastery, ...) plus 'decided_by' => 'ai'|'rule'
     */
    public function currentPathway($userid, $competencyId) {
        if (self::DECISION_MODE === 'ai') {
            $stored = $this->storedDecision($userid, $competencyId);
            if ($stored !== null) {
                return $stored;
            }
        }
        $result = $this->computeLearningPathway($userid, $competencyId, 'quiz');
        $result['decided_by'] = 'rule';
        return $result;
    }

    /** Per-request memo for storedDecision(), keyed by userid. */
    private $storedtrackcache = [];

    /**
     * The stored AI decision row for one competency, or null when the
     * student has no AI-decided track (legacy rule-era tracks return null
     * too, so they keep being gated by the formula they were made with).
     */
    public function storedDecision($userid, $competencyId) {
        $track = $this->storedTrack($userid);
        if ($track === null || (($track['decision']['by'] ?? null) !== 'ai')) {
            return null;
        }
        foreach ($track['competencies'] as $row) {
            if ((int) $row['competency_id'] === (int) $competencyId) {
                $row['decided_by'] = 'ai';
                return $row;
            }
        }
        return null;
    }

    /** The decoded stored track for a user, or null. Memoised per instance. */
    public function storedTrack($userid) {
        $userid = (int) $userid;
        if (!array_key_exists($userid, $this->storedtrackcache)) {
            $db = get_db();
            $stmt = $db->prepare("SELECT track_json FROM acculearn_learning_tracks WHERE userid = ?");
            $stmt->execute([$userid]);
            $row = $stmt->fetch();
            $track = $row ? json_decode($row->track_json, true) : null;
            $this->storedtrackcache[$userid] = (is_array($track) && !empty($track['competencies'])) ? $track : null;
        }
        return $this->storedtrackcache[$userid];
    }

    /**
     * Refreshes the FACT fields of stored decision rows from live evidence,
     * leaving the decision fields (mastery, lp, priority, rationale...) as
     * the model made them. Used by the track page so a regraded quiz shows
     * its real grade while the pathway stays whatever was actually decided.
     *
     * @return array the rows in their stored (adaptive) order, plus
     *   'evidence_stale' => true on every row when the live evidence no
     *   longer matches what the decision was made on.
     */
    public function applyLiveEvidence(array $storedrows, array $evidence) {
        $live = [];
        foreach ($evidence as $e) {
            $live[(int) $e['competency_id']] = $e;
        }
        $stale = self::evidenceSignature($storedrows) !== self::evidenceSignature($evidence);

        $factkeys = ['cm', 'cmi', 'gi', 'attempted', 'quizzes', 'formatives_passed',
            'summative_passed', 'all_passed', 'quizzes_passed', 'quizzes_total'];
        foreach ($storedrows as &$row) {
            $e = $live[(int) $row['competency_id']] ?? null;
            if ($e !== null) {
                foreach ($factkeys as $k) {
                    if (array_key_exists($k, $e)) {
                        $row[$k] = $e[$k];
                    }
                }
            }
            $row['evidence_stale'] = $stale;
        }
        unset($row);
        return $storedrows;
    }

    /**
     * The RULE decision for one competency: the LP_MODE formula applied to
     * computeEvidence(). Under DECISION_MODE 'ai' this is the fallback only;
     * see currentPathway() for what the gate actually uses.
     */
    public function computeLearningPathway($userid, $competencyId, $source = 'quiz') {
        $evidence = $this->computeEvidence($userid, $competencyId, $source);
        $stats = ['cm' => $evidence['cm'], 'attempted' => $evidence['attempted']];

        $pr = $this->checkPrerequisite($userid, $competencyId, $source);

        $cm = $evidence['cm'];
        $cmi = $evidence['cmi'];
        $gi = $evidence['gi'];

        $quizstatus = [
            'quizzes' => $evidence['quizzes'],
            'formatives_passed' => $evidence['formatives_passed'],
            'summative_passed' => $evidence['summative_passed'],
            'all_passed' => $evidence['all_passed'],
            'passed_count' => $evidence['quizzes_passed'],
            'total_count' => $evidence['quizzes_total'],
        ];
        $allpassed = $quizstatus['all_passed'];

        if (self::LP_MODE === 'paper') {
            // Thesis Chapter 3, verbatim:
            //   LP = 1  if PR = 0                                 Prerequisite Review
            //   LP = 2  if PR = 1 and CM < 75                     Guided Remediation
            //   LP = 3  if PR = 1 and 75 <= CM < 85               Reinforcement Practice
            //   LP = 3  if PR = 1 and CM >= 85 and GI  >= 0.20    Reinforcement (guessing-driven)
            //   LP = 4  if PR = 1 and CM >= 85 and CMI <  0.20    Advancement
            //
            // The manuscript leaves one combination unstated: CM >= 85 with a
            // LOW GI but a HIGH CMI. Its own prose resolves it - "a high
            // Confidence Misconception Index added targeted explanations and
            // corrective practice" - which is Reinforcement Practice, not
            // Advancement, so that case routes to LP=3 here. This is the same
            // reading recorded in PROJECT_HANDOFF.md and confirmed with the
            // thesis author; it is called out because it is an interpretation,
            // not something the paper states outright.
            $mastery = $this->classifyMastery($cm, $stats['attempted']);
            $holdreason = null;

            if ($pr === 0) {
                $lp = 1;
            } elseif ($cm === null) {
                $lp = null;                                  // nothing attempted yet
            } elseif ($cm < 75) {
                $lp = 2;
            } elseif ($cm < 85) {
                $lp = 3;
            } elseif ($gi !== null && $gi >= self::GI_GUESSING_THRESHOLD) {
                $lp = 3;
                $holdreason = 'Strong score, but several answers were marked unsure - practice to confirm';
            } elseif ($cmi !== null && $cmi >= self::CMI_MISCONCEPTION_THRESHOLD) {
                $lp = 3;
                $holdreason = 'Strong score, but confident wrong answers suggest a misconception to clear';
            } else {
                $lp = 4;
            }

            // A competency can only be called Mastered on a real sample, so a
            // CM computed from too few items never advances, whatever it reads.
            if ($lp === 4 && $mastery !== 'Mastered') {
                $lp = 3;
                $holdreason = 'Not enough answered items yet to confirm mastery';
            }

            $lplabel = $holdreason ?? $this->lpLabel($lp);

            return [
                'competency_id' => $competencyId,
                'cm' => $cm,
                'cmi' => $cmi,
                'gi' => $gi,
                'pr' => $pr,
                'mastery' => $mastery,
                'attempted' => $stats['attempted'],
                'lp' => $lp,
                'lp_label' => $lplabel,
                'quizzes' => $quizstatus['quizzes'],
                'formatives_passed' => $quizstatus['formatives_passed'],
                'summative_passed' => $quizstatus['summative_passed'],
                'quizzes_passed' => $quizstatus['passed_count'],
                'quizzes_total' => $quizstatus['total_count'],
            ];
        }

        // ---- LP_MODE === 'quizpassing' (the post-study revision) -------------
        // Mastery is earned by PASSING QUIZZES, not by a pooled average.
        // Every formative plus the summative must be passed; CM/CMI/GI remain
        // as diagnostics that shape the guidance, but no longer decide the gate.
        $mastery = $allpassed
            ? 'Mastered'
            : $this->bandBelowMastered($cm, $stats['attempted']);

        if ($pr === 0) {
            $lp = 1;                       // prerequisite competency not yet passed
        } elseif ($allpassed) {
            $lp = 4;                       // every quiz passed - advance
        } elseif ($cm === null) {
            $lp = null;                    // nothing attempted yet
        } elseif ($cm < 75) {
            $lp = 2;                       // guided remediation
        } else {
            $lp = 3;                       // on track, quizzes still outstanding
        }

        // Label the specific reason a non-mastered competency is held, so the
        // student is never told "advance" while a gate is visibly shut.
        if ($allpassed) {
            $lplabel = $this->lpLabel(4);
        } else if ($pr === 0) {
            $lplabel = $this->lpLabel(1);
        } else if ($quizstatus['total_count'] === 0) {
            $lplabel = $this->lpLabel($lp);
        } else if (!$quizstatus['formatives_passed']) {
            $lplabel = 'Pass every formative quiz to unlock the summative';
        } else {
            $lplabel = 'Pass the summative quiz to master this competency';
        }

        return [
            'competency_id' => $competencyId,
            'cm' => $cm,
            'cmi' => $cmi,
            'gi' => $gi,
            'pr' => $pr,
            'mastery' => $mastery,
            'attempted' => $stats['attempted'],
            'lp' => $lp,
            'lp_label' => $lplabel,
            // Per-quiz detail so the track can show exactly which quizzes are
            // still outstanding rather than only a percentage.
            'quizzes' => $quizstatus['quizzes'],
            'formatives_passed' => $quizstatus['formatives_passed'],
            'summative_passed' => $quizstatus['summative_passed'],
            'quizzes_passed' => $quizstatus['passed_count'],
            'quizzes_total' => $quizstatus['total_count'],
        ];
    }

    private function lpLabel($lp) {
        switch ($lp) {
            case 1: return 'Prerequisite Review';
            case 2: return 'Guided Remediation';
            // LP=3 is the Developing (75-84%) branch and the high-GI branch,
            // both of which trigger reinforcement practice rather than
            // remediation. It previously carried LP=2's label verbatim, so a
            // student scoring under 75% and a student scoring 85%+ while
            // guessing saw identical wording and could not tell the two apart.
            case 3: return 'Reinforcement Practice';
            case 4: return 'Advancement to Next Competency';
            default: return 'Not Yet Assessed';
        }
    }

    public function computeFullTrack($userid, $source = 'quiz') {
        $db = get_db();
        $competencies = $db->query("SELECT * FROM acculearn_competencies ORDER BY sequence")->fetchAll();

        $track = [];
        foreach ($competencies as $c) {
            $result = $this->computeLearningPathway($userid, $c->id, $source);
            $result['competency_name'] = $c->name;
            $result['sequence'] = (int) $c->sequence;
            // Each competency IS a Moodle course here, so carrying the course
            // id lets the student's track link straight to the material rather
            // than only naming it.
            $result['courseid'] = $c->courseid === null ? null : (int) $c->courseid;
            $track[] = $result;
        }
        return $this->prioritize($track);
    }

    /**
     * Turns the fixed co1..co7 list into an ADAPTIVE order driven by the
     * student's own evidence (pre-test first, then live quiz performance).
     *
     * The prerequisite chain is a real pedagogical dependency - you cannot
     * journalize before you know the five major accounts - so this does NOT
     * permute the chain and does NOT skip, hide or newly lock anything.
     * Every competency stays in the track and stays required. What adapts is
     * the ORDER things are presented in and which single competency is
     * called out as "do this next":
     *
     *   next     - the frontier: the first competency, in chain order, whose
     *              prerequisite is satisfied and which is not yet Mastered.
     *              A strong pre-test moves this forward, so a student who
     *              already knows co1-co3 starts at co4 instead of grinding
     *              through material they have demonstrably mastered.
     *   revisit  - Mastered, but with a Confidence Misconception Index at or
     *              above the threshold: answered confidently AND wrongly
     *              often enough to suggest a real misconception hiding
     *              behind a passing score. Surfaced ABOVE upcoming work
     *              because a wrong-but-confident foundation propagates
     *              forward through the chain. Advisory only - it never
     *              re-locks the competency or blocks progression.
     *   upcoming - not yet mastered and not the frontier; kept in chain
     *              order, since that is the order they unlock in.
     *   maintain - Mastered and no misconception signal. Ordered weakest
     *              first, so optional review effort goes where the margin
     *              is thinnest.
     */
    private function prioritize(array $track) {
        // Frontier: first unlocked, not-yet-mastered competency in chain order.
        $frontier = null;
        foreach ($track as $t) {
            if ((int) $t['pr'] === 1 && $t['mastery'] !== 'Mastered') {
                $frontier = $t['competency_id'];
                break;
            }
        }

        foreach ($track as &$t) {
            $mastered = ($t['mastery'] === 'Mastered');
            $misconception = $mastered
                && $t['cmi'] !== null
                && $t['cmi'] >= self::CMI_MISCONCEPTION_THRESHOLD;

            if ($t['competency_id'] === $frontier) {
                $t['priority_group'] = 'next';
                $t['priority_rank'] = 0;
                // Say exactly which quizzes are outstanding. "Still below
                // mastery" is useless guidance when what the student actually
                // needs is a specific quiz they have not passed yet.
                $outstanding = [];
                foreach (($t['quizzes'] ?? []) as $q) {
                    if (!$q['passed']) { $outstanding[] = $q['name']; }
                }
                if (empty($t['quizzes'])) {
                    $t['priority_reason'] =
                        'This is where your path continues - you have not been assessed on it yet.';
                } else if (!($t['formatives_passed'] ?? false)) {
                    $t['priority_reason'] = 'Pass every formative quiz here to unlock the summative. '
                        . 'Still to pass: ' . implode(', ', $outstanding) . '.';
                } else {
                    $t['priority_reason'] = 'All formative quizzes passed - the summative is now '
                        . 'unlocked. Pass it to master this competency and open the next one.';
                }
            } else if ($misconception) {
                $t['priority_group'] = 'revisit';
                $t['priority_rank'] = 1;
                $t['priority_reason'] =
                    'You passed this, but several answers were confidently incorrect - worth a second look '
                    . 'before it affects later topics.';
            } else if (!$mastered) {
                $t['priority_group'] = 'upcoming';
                $t['priority_rank'] = 2;
                $t['priority_reason'] = ((int) $t['pr'] === 0)
                    ? 'Unlocks once you master the competency it builds on.'
                    : 'Still ahead of you on your path.';
            } else {
                $t['priority_group'] = 'maintain';
                $t['priority_rank'] = 3;
                $t['priority_reason'] = 'Already mastered - revisit any time to keep it fresh.';
            }

            $t['blocked'] = ((int) $t['pr'] === 0);
            $t['is_next'] = ($t['competency_id'] === $frontier);
            $t['decided_by'] = 'rule';
        }
        unset($t);

        usort($track, function ($a, $b) {
            if ($a['priority_rank'] !== $b['priority_rank']) {
                return $a['priority_rank'] <=> $b['priority_rank'];
            }
            // Worst misconception first.
            if ($a['priority_group'] === 'revisit') {
                return ($b['cmi'] ?? 0) <=> ($a['cmi'] ?? 0);
            }
            // Thinnest mastery margin first.
            if ($a['priority_group'] === 'maintain') {
                return ($a['cm'] ?? 0) <=> ($b['cm'] ?? 0);
            }
            // Everything else follows the chain, which is the order it unlocks in.
            return $a['sequence'] <=> $b['sequence'];
        });

        return $track;
    }
